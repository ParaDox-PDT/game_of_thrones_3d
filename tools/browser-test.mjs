import { chromium } from '@playwright/test';
import assert from 'node:assert/strict';
import { mkdir, writeFile } from 'node:fs/promises';
const reportDirectory=process.env.TEST_REPORT_DIR || 'artifacts/reference-pass-05/browser';
await mkdir(reportDirectory,{recursive:true});
const browser=await chromium.launch({channel:'chrome',headless:true,args:['--enable-webgl','--ignore-gpu-blocklist']});
const context=await browser.newContext({viewport:{width:1440,height:1000},deviceScaleFactor:1});
const page=await context.newPage();
const errors=[];
const failures=[];
page.on('pageerror',error=>errors.push(error.message));
page.on('requestfailed',request=>failures.push({url:request.url(),error:request.failure()?.errorText}));
const response=await page.goto(process.env.TEST_URL||'http://127.0.0.1:3000',{waitUntil:'networkidle',timeout:120000});
assert.equal(response.status(),200);
await page.getByRole('button',{name:'Enter the courtyard'}).waitFor({timeout:90000});
await page.waitForFunction(()=>window.__world?.loaded,{timeout:90000});
await page.waitForFunction(()=>window.__world?.calls>0,{timeout:90000});
const initial=await page.evaluate(()=>({...window.__world,renderer:document.querySelector('canvas').getContext('webgl2')?.getParameter(7937),heap:performance.memory?.usedJSHeapSize}));
assert.ok(initial.triangles>10000);
await page.screenshot({path:`${reportDirectory}/browser-overview.png`});
await page.getByRole('button',{name:'Map plan',exact:false}).click();
await page.waitForFunction(()=>window.__world?.cameraType==='OrthographicCamera');
await page.screenshot({path:`${reportDirectory}/browser-map-plan.png`});
await page.getByRole('button',{name:'Godswood',exact:false}).click();
await page.waitForFunction(()=>window.__world?.place==='Godswood' && window.__world?.cameraType==='PerspectiveCamera');
await page.screenshot({path:`${reportDirectory}/browser-godswood.png`});
await page.getByRole('button',{name:'Gatehouse',exact:false}).click();
await page.screenshot({path:`${reportDirectory}/browser-gatehouse.png`});
await page.getByRole('button',{name:'Dawn',exact:true}).click();
await page.getByRole('button',{name:'Blue hour',exact:true}).click();
assert.equal(await page.getByRole('button',{name:'Blue hour',exact:true}).getAttribute('aria-pressed'),'true');
await page.getByRole('button',{name:'Overcast',exact:true}).click();
await page.getByRole('button',{name:'Enter the courtyard'}).click();
await page.keyboard.down('Shift');
await page.keyboard.down('w');
await page.waitForFunction(()=>window.__world?.position[2]<175,null,{timeout:90000});
await page.keyboard.up('w');
await page.keyboard.up('Shift');
const courtyard=await page.evaluate(()=>window.__world);
assert.ok(courtyard.position[2]<175);
assert.ok(courtyard.position[2]>155);
await page.screenshot({path:`${reportDirectory}/browser-courtyard.png`});
await page.keyboard.down('Shift');
await page.keyboard.down('w');
await page.waitForFunction(()=>window.__world?.position[2]<=124.05,null,{timeout:60000});
await page.keyboard.up('w');
const keepStop=await page.evaluate(()=>window.__world);
await page.keyboard.up('Shift');
assert.ok(keepStop.position[2]>123.5,'Player crossed the Great Hall facade');
await page.keyboard.press('Escape');
await page.waitForFunction(()=>!document.pointerLockElement);
await page.getByRole('button',{name:'Return to atlas'}).click();
await page.getByRole('button',{name:'Asset library'}).click();
await page.getByRole('dialog',{name:'Asset library'}).waitFor();
assert.equal(await page.locator('a[download]').count(),23);
assert.ok((await page.locator('a[download]').first().getAttribute('href')).includes('winterfell-reference'));
await page.getByRole('button',{name:'Close panel'}).click();
await page.setViewportSize({width:390,height:844});
await page.screenshot({path:`${reportDirectory}/browser-mobile.png`});
const mobile=await page.evaluate(()=>({scrollWidth:document.documentElement.scrollWidth,width:innerWidth,canvasWidth:document.querySelector('canvas').width}));
assert.equal(mobile.scrollWidth,mobile.width);
assert.equal(errors.length,0,JSON.stringify(errors));
assert.equal(failures.length,0,JSON.stringify(failures));
const report={passed:true,url:page.url(),createdAt:new Date().toISOString(),initial,courtyard,hallFacadeStop:keepStop,mobile,errors,failures,notes:'Headless Chrome on this workstation; FPS is measured locally and is not a hardware guarantee.'};
await writeFile(`${reportDirectory}/browser-validation.json`,JSON.stringify(report,null,2));
console.log(JSON.stringify(report,null,2));
await browser.close();

import { readFile,writeFile } from 'node:fs/promises';
import assert from 'node:assert/strict';
import {moveCapsule,floorAt} from '../lib/collision.mjs';
const folder='public/assets/winterfell-environment/';
const current=JSON.parse(await readFile(folder+'layout.json','utf8'));
const old=JSON.parse(await readFile('public/assets/winterfell-detailed/layout.json','utf8'));
for(const field of ['footprintMetres','buildings','courtyards','zones','gates','routes'])assert.deepEqual(current[field],old[field],`Changed ${field}`);
assert.deepEqual(current.terrainMetres,[1280,1280]);
const manifest=JSON.parse(await readFile(folder+'manifest.json','utf8'));
const counts=manifest.environmentDetails;
for(const [key,min] of Object.entries({pines:350,mountainRanges:4,rocks:150,snowDrifts:300,barrels:20,crates:16,carts:4,woodPiles:8,fenceSegments:5,torches:12,braziers:6,banners:8,marketStalls:4,footprints:100,wheelRuts:10}))assert.ok(counts[key]>=min,`${key} missing`);
assert.equal(manifest.torchLights,18);
const data=JSON.parse(await readFile(folder+'collision.json','utf8'));
const hf=data.terrainHeightField;
assert.equal(hf.heights.length,hf.columns*hf.rows);
assert.ok(hf.heights.every(Number.isFinite));
assert.ok(Math.abs(floorAt(0,125,.12,data)-.12)<.001,'Approach must stay flat');
assert.ok(Math.abs(floorAt(0,0,.12,data)-.12)<.001,'Courtyard support changed');
function walk(p,delta,count){for(let i=0;i<count;i++)p=moveCapsule(p,delta,data);return p;}
let inner=walk([-60,1.92,-36.6],[0,-.05],580);
assert.ok(inner[1]>14.5,'Snow obstructs inner stair');
inner=walk(inner,[-.05,0],75);assert.ok(inner[0]<-63.5,'Inner landing blocked');
let outer=walk([-44.3,1.92,-91],[.05,0],446);
assert.ok(outer[1]>11.7,'Snow obstructs outer stair');
outer=walk(outer,[0,-.05],55);assert.ok(outer[2]<-93.5,'Outer landing blocked');
const files=['overview.png','southern-approach.png','market-street.png','stable-yard.png','inner-courtyard.png','winter-landscape.png','blue-hour.png'];
for(const file of files)assert.ok((await readFile(folder+file)).length>100000,`Missing preview ${file}`);
const report={passed:true,fortressLayoutPreserved:true,terrainMetres:current.terrainMetres,counts,embeddedTorchLights:manifest.torchLights,heightfieldSamples:hf.heights.length,wallStairsClear:true,previewCount:files.length};
await writeFile('artifacts/environment-pass-04/environment-validation.json',JSON.stringify(report,null,2));
console.log(JSON.stringify(report,null,2));
